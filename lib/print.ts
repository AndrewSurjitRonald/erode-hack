/**
 * Opens a blank tab synchronously (must run inside the click handler so pop-up blockers allow it).
 * Returns a writer to fill it in later, e.g. after an async fetch.
 */
export function openPrintWindow(): ((title: string, bodyHtml: string) => void) | null {
  const win = window.open("", "_blank");
  if (!win) return null;
  win.document.write("<p style='font-family:sans-serif;padding:40px'>Preparing…</p>");
  return (title, bodyHtml) => {
    win.document.open();
    win.document.write(`<!DOCTYPE html>
<html>
  <head><meta charset="utf-8" /><title>${escapeHtml(title)}</title><style>${BASE_STYLES}</style></head>
  <body>
    <div class="no-print" style="margin-bottom: 20px;">
      <button onclick="window.print()" style="background:#0F172A;color:white;padding:10px 20px;border-radius:8px;font-weight:bold;border:none;cursor:pointer;">🖨️ Print / Save as PDF</button>
    </div>
    ${bodyHtml}
    <div class="footer">Generated by PathLearn Adaptive Learning Engine · ${escapeHtml(new Date().toLocaleString())}</div>
  </body>
</html>`);
    win.document.close();
  };
}

/** Numbered questions with blank workspace, grouped by section, plus an answer key on a new page. */
export function worksheetHtml(sections: { title: string; questions: PrintableQuestion[] }[]): string {
  let n = 0;
  const answers: string[] = [];
  const body = sections
    .map((section) => {
      const items = section.questions
        .map((q) => {
          n++;
          answers.push(
            `<tr><td>${n}</td><td>${String.fromCharCode(65 + q.answerIdx)}</td><td>${escapeHtml(
              q.options[q.answerIdx] ?? ""
            )}</td></tr>`
          );
          return `<div class="question">
            <strong>Q${n}.</strong> ${escapeHtml(q.text)}<span class="badge">Level ${q.difficulty}</span>
            <div class="options">${q.options
              .map((o, i) => `<div>(${String.fromCharCode(65 + i)}) ${escapeHtml(o)}</div>`)
              .join("")}</div>
            <div class="workspace"></div>
          </div>`;
        })
        .join("");
      return `<div class="section"><div class="section-title">${escapeHtml(section.title)}</div>${items}</div>`;
    })
    .join("");

  return `${body}
    <div class="answer-key">
      <div class="section-title">Answer Key (for the teacher)</div>
      <table><thead><tr><th>Q</th><th>Option</th><th>Answer</th></tr></thead><tbody>${answers.join("")}</tbody></table>
    </div>`;
}
