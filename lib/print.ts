export type PrintableQuestion = {
  text: string;
  options: string[];
  answerIdx: number;
  difficulty: number;
  topicName: string;
};

export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

